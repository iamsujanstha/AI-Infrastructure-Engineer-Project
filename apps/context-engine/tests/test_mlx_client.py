import json
import re
import threading
from http.server import BaseHTTPRequestHandler, HTTPServer

import pytest

from mlx_client import MlxConfigurationError, MlxRequestError, generate


def _serve(payload, status=200, extra_headers=None):
    received = {}

    class Handler(BaseHTTPRequestHandler):
        def do_POST(self):
            received["path"] = self.path
            received["body"] = json.loads(self.rfile.read(int(self.headers["Content-Length"])))
            body = json.dumps(payload).encode()
            self.send_response(status)
            self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", str(len(body)))
            for name, value in (extra_headers or {}).items():
                self.send_header(name, value)
            self.end_headers()
            self.wfile.write(body)

        def log_message(self, _format, *_args):
            return

    server = HTTPServer(("127.0.0.1", 0), Handler)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    return server, thread, received


def _close(server, thread):
    server.shutdown()
    server.server_close()
    thread.join(timeout=2)


@pytest.fixture(autouse=True)
def configured_context_window(monkeypatch):
    monkeypatch.setenv("MLX_CONTEXT_WINDOW_TOKENS", "4096")


def test_sends_bounded_non_streaming_request_to_loopback_server():
    server, thread, received = _serve({
        "choices": [{"message": {"content": "Generated by the test server."}}],
    })
    try:
        result = generate(
            "Explain the adapter boundary.",
            base_url=f"http://127.0.0.1:{server.server_port}/v1",
            model="local-test-model",
            timeout_seconds=3,
            max_output_tokens=128,
        )
    finally:
        _close(server, thread)

    assert result.text == "Generated by the test server."
    system_message = received["body"]["messages"][0]["content"]
    assert re.search(r"current local date and time is \d{4}-\d{2}-\d{2}T", system_message)
    assert result.prompt_token_estimate == len(system_message.encode()) + len(b"Explain the adapter boundary.") + 256
    assert result.reserved_output_tokens == 128
    assert result.context_window_tokens == 4096
    assert received["path"] == "/v1/chat/completions"
    assert received["body"] == {
        "model": "local-test-model",
        "messages": [
            {"role": "system", "content": system_message},
            {"role": "user", "content": "Explain the adapter boundary."},
        ],
        "max_tokens": 128,
        "stream": False,
    }


def test_uses_verified_model_and_budget_defaults_when_shell_vars_are_missing(monkeypatch):
    monkeypatch.delenv("MLX_MODEL", raising=False)
    monkeypatch.delenv("MLX_CONTEXT_WINDOW_TOKENS", raising=False)
    server, thread, received = _serve({
        "choices": [{"message": {"content": "Default model response."}}],
    })
    try:
        result = generate(
            "Hello.",
            base_url=f"http://127.0.0.1:{server.server_port}",
            timeout_seconds=3,
        )
    finally:
        _close(server, thread)

    assert result.text == "Default model response."
    assert result.context_window_tokens == 8192
    assert received["body"]["model"] == "mlx-community/Qwen3-8B-4bit"


def test_sends_prior_turns_and_counts_them_in_context_budget():
    history = [
        {"role": "user", "content": "My project uses PostgreSQL."},
        {"role": "assistant", "content": "Understood. I will keep that in mind."},
    ]
    server, thread, received = _serve({
        "choices": [{"message": {"content": "A follow-up answer."}}],
    })
    try:
        result = generate(
            "What database does it use?",
            history=history,
            base_url=f"http://127.0.0.1:{server.server_port}",
            timeout_seconds=3,
        )
    finally:
        _close(server, thread)

    messages = received["body"]["messages"]
    assert [message["role"] for message in messages] == ["system", "user", "assistant", "user"]
    assert [message["content"] for message in messages[1:]] == [
        "My project uses PostgreSQL.",
        "Understood. I will keep that in mind.",
        "What database does it use?",
    ]
    assert result.prompt_token_estimate == sum(len(message["content"].encode()) for message in messages) + 256


def test_rejects_incomplete_or_misordered_history():
    with pytest.raises(MlxConfigurationError, match="complete user/assistant messages"):
        generate("Follow up", history=[{"role": "assistant", "content": "No preceding user message."}])
    with pytest.raises(MlxConfigurationError, match="invalid message sequence"):
        generate("Follow up", history=[
            {"role": "assistant", "content": "Wrong first role."},
            {"role": "user", "content": "Wrong second role."},
        ])


@pytest.mark.parametrize("url", [
    "https://127.0.0.1:8080",
    "http://example.com:8080",
    "http://127.0.0.1:8080/private/path",
    "http://user@127.0.0.1:8080",
])
def test_rejects_non_loopback_or_unexpected_endpoint(url):
    with pytest.raises(MlxConfigurationError):
        generate("hello", base_url=url, model="local-test-model")


def test_rejects_missing_model_and_oversized_prompt():
    with pytest.raises(MlxConfigurationError, match="Set MLX_MODEL"):
        generate("hello", base_url="http://127.0.0.1:8080", model="")
    with pytest.raises(MlxConfigurationError, match="32000 characters"):
        generate("x" * 32_001, base_url="http://127.0.0.1:8080", model="local-test-model")


def test_rejects_prompt_before_provider_call_when_budget_is_exceeded():
    with pytest.raises(MlxConfigurationError, match="exceeds MLX_CONTEXT_WINDOW_TOKENS"):
        generate(
            "too large",
            base_url="http://127.0.0.1:8080",
            model="local-test-model",
            max_output_tokens=512,
            context_window_tokens=700,
        )


def test_rejects_malformed_model_response():
    server, thread, _ = _serve({"choices": []})
    try:
        with pytest.raises(MlxRequestError, match="invalid chat completion"):
            generate("hello", base_url=f"http://127.0.0.1:{server.server_port}", model="local-test-model", timeout_seconds=3)
    finally:
        _close(server, thread)


def test_reports_provider_unavailable_without_leaking_endpoint_details():
    server, thread, _ = _serve({"detail": "unavailable"}, status=503)
    try:
        with pytest.raises(MlxRequestError, match="unavailable or timed out"):
            generate("hello", base_url=f"http://127.0.0.1:{server.server_port}", model="local-test-model", timeout_seconds=3)
    finally:
        _close(server, thread)


def test_does_not_follow_redirects_from_the_local_server():
    server, thread, _ = _serve({}, status=302, extra_headers={"Location": "http://example.com/"})
    try:
        with pytest.raises(MlxRequestError, match="unavailable or timed out"):
            generate("hello", base_url=f"http://127.0.0.1:{server.server_port}", model="local-test-model", timeout_seconds=3)
    finally:
        _close(server, thread)
